// Pin the Kotlin module name for every Android variant (internal names are mangled with it).
// The androidTarget setting alone yields `adapty_ui_release_debug` in debug: KGP appends the variant.
tasks.withType<KotlinCompile>().configureEach {
    compilerOptions.moduleName.set("adapty-ui_release")
}

// isIncludeAndroidResources enables an AAR metadata check for unit tests that rejects compileSdk 31
// (activity 1.8.2 / Compose 1.8.x ask for 33+). compileSdk stays as is; only the unit-test check is off.
tasks.matching { it.name.matches(Regex("check.*UnitTestAarMetadata")) }.configureEach {
    enabled = false
}

// Absolute fixture dir for karma.config.d/fixtures.js (machine-specific, git-ignored)
val generateKarmaPaths by tasks.registering {
    val fixturesDir = layout.projectDirectory.dir("src/androidUnitTest/resources/calm-onboarding").asFile.absolutePath
    val out = layout.projectDirectory.file("karma.config.d/paths.js")
    inputs.property("fixturesDir", fixturesDir)
    outputs.file(out)
    doLast {
        out.asFile.writeText(
            "// Generated by :adapty-ui:generateKarmaPaths. Do not edit.\n" +
                "function adaptyUiFixturesDir() { return \"${fixturesDir.replace("\\", "\\\\").replace("\"", "\\\"")}\"; }\n"
        )
    }
}
tasks.matching { it.name == "wasmJsBrowserTest" }.configureEach {
    dependsOn(generateKarmaPaths)
    // Karma config and served fixtures are not tracked by KGP
    inputs.dir(layout.projectDirectory.dir("karma.config.d"))
    inputs.dir(layout.projectDirectory.dir("src/androidUnitTest/resources/calm-onboarding"))
}

