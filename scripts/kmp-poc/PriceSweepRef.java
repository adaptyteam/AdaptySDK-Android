// Generates adapty-ui/src/wasmJsTest/.../text/PriceSweepTable.kt: Android PriceConverter + core PriceFormatter(Locale.US)
// outputs computed with java.math.BigDecimal. Run: java scripts/kmp-poc/PriceSweepRef.java > <that file>
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.text.NumberFormat;
import java.util.Locale;

public class PriceSweepRef {
    static BigDecimal div(BigDecimal a, int d) { return a.divide(BigDecimal.valueOf(d), 4, RoundingMode.CEILING); }
    static BigDecimal mul(BigDecimal a, int m) { return a.multiply(BigDecimal.valueOf(m)); }

    static String fmt(BigDecimal v) {
        NumberFormat i = NumberFormat.getInstance(Locale.US); i.setMaximumFractionDigits(0); i.setGroupingUsed(true);
        NumberFormat d = NumberFormat.getInstance(Locale.US); d.setMinimumFractionDigits(2); d.setGroupingUsed(true);
        try { return i.format(v.toBigIntegerExact()); } catch (ArithmeticException e) { return d.format(v.setScale(2, RoundingMode.CEILING)); }
    }

    public static void main(String[] args) {
        String[] prices = {"0.01", "0.9", "0.99", "1.99", "2.99", "4.5", "4.9", "4.99", "5.1", "9.99", "12", "14.99",
            "19.99", "29.99", "39.99", "49.99", "59.99", "79.99", "99.99", "149.99", "1234.56", "0.333"};
        int[] counts = {1, 2, 3, 5, 10, 30};
        StringBuilder sb = new StringBuilder();
        sb.append("package com.adapty.ui.internal.text\n\n");
        sb.append("// Generated by scripts/kmp-poc/PriceSweepRef.java (java.math.BigDecimal + NumberFormat(Locale.US)); do not edit.\n");
        sb.append("// Row: price unit numberOfUnits yearly|monthly|weekly|daily (PriceConverter + PriceFormatter.format)\n");
        sb.append("internal val PRICE_SWEEP_TABLE: String = \"\"\"\n");
        for (String s : prices) {
            BigDecimal p = new BigDecimal(s);
            for (String u : new String[]{"D", "W", "M", "Y"}) for (int n : counts) {
                int uy = u.equals("Y") ? 1 : u.equals("M") ? 12 : u.equals("W") ? 52 : 365;
                BigDecimal y = mul(div(p, n), uy);
                int dv, mu;
                if (u.equals("Y")) { dv = 12 * n; mu = 1; } else if (u.equals("M")) { dv = n; mu = 1; } else if (u.equals("W")) { dv = 7 * n; mu = 30; } else { dv = n; mu = 30; }
                BigDecimal mo = mul(div(p, dv), mu);
                BigDecimal w;
                if (u.equals("D")) w = div(mul(p, 7), n);
                else if (u.equals("M")) w = div(mul(p, 7), 30 * n);
                else w = div(p, (u.equals("Y") ? 52 : 1) * n);
                int diu = u.equals("Y") ? 365 : u.equals("M") ? 30 : u.equals("W") ? 7 : 1;
                BigDecimal d = div(p, diu * n);
                sb.append(s).append(' ').append(u).append(' ').append(n).append(' ')
                    .append(fmt(y)).append('|').append(fmt(mo)).append('|').append(fmt(w)).append('|').append(fmt(d)).append('\n');
            }
        }
        sb.append("\"\"\"\n");
        System.out.print(sb.toString().replace("$", "\\$"));
    }
}
